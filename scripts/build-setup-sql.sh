#!/usr/bin/env bash
# Concatenate every migration into ONE file you can paste into the Supabase
# SQL editor (works from a phone). Re-run after adding a migration.
#   scripts/build-setup-sql.sh          write supabase/setup.sql
#   scripts/build-setup-sql.sh --check  fail if supabase/setup.sql is stale (CI)
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/supabase/setup.sql"
tmp="$(mktemp)"
{
  echo "-- SAM Inventory: complete database setup (generated by scripts/build-setup-sql.sh)."
  echo "-- Paste ALL of this into Supabase -> SQL Editor -> New query -> Run. Run it once, on an empty project."
  echo
  for f in "$root"/supabase/migrations/*.sql; do
    echo "-- ===================== $(basename "$f") ====================="
    cat "$f"
    echo
  done
} > "$tmp"
if [ "${1:-}" = "--check" ]; then
  diff -q "$tmp" "$out" >/dev/null || { echo "supabase/setup.sql is stale: run scripts/build-setup-sql.sh"; rm -f "$tmp"; exit 1; }
  rm -f "$tmp"; echo "setup.sql is up to date"
else
  mv "$tmp" "$out"; echo "wrote $out ($(wc -l < "$out") lines)"
fi
